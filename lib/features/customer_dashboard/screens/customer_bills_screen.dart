import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:printing/printing.dart';
import '../../../core/constants/app_colors.dart';
import '../../../core/localization/app_localizations.dart';
import '../../../core/localization/locale_provider.dart';
import '../../../core/services/pdf_service.dart';
import '../../../core/utils/currency_formatter.dart';
import '../../../core/utils/date_formatter.dart';
import '../../../core/widgets/empty_state_widget.dart';
import '../../auth/providers/auth_provider.dart';
import '../../billing/models/monthly_bill_model.dart';
import '../../billing/repositories/billing_repository.dart';
import '../../customers/repositories/customer_repository.dart';
import '../../milk_entry/repositories/milk_entry_repository.dart';
import '../../settings/models/dairy_settings_model.dart';
import '../../payments/screens/upi_payment_screen.dart';

class CustomerBillsScreen extends StatelessWidget {
  const CustomerBillsScreen({super.key});

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final user = context.watch<AuthProvider>().currentUser;
    final customerId = user?.customerId;

    if (customerId == null) {
      return Scaffold(
        appBar: AppBar(title: Text(context.tr('my_bills'))),
        body: const Center(child: Text('Customer profile not linked')),
      );
    }

    return Scaffold(
      appBar: AppBar(
        title: Text(context.tr('my_bills')),
      ),
      body: StreamBuilder<List<MonthlyBillModel>>(
        stream: BillingRepository().getCustomerBillsStream(customerId),
        builder: (ctx, snapshot) {
          if (snapshot.connectionState == ConnectionState.waiting) {
            return const Center(child: CircularProgressIndicator());
          }

          final bills = snapshot.data ?? [];
          if (bills.isEmpty) {
            return EmptyStateWidget(
              title: 'No Monthly Bills Generated',
              message: 'डेअरी मालकाने मासिक बिल तयार केल्यावर येथे दिसेल.\nBills generated by the dairy will appear here.',
              icon: Icons.receipt_long_rounded,
            );
          }

          return ListView.builder(
            padding: const EdgeInsets.all(16),
            itemCount: bills.length,
            itemBuilder: (ctx, index) {
              final bill = bills[index];
              return _buildBillCard(ctx, bill, isDark);
            },
          );
        },
      ),
    );
  }

  Widget _buildBillCard(BuildContext context, MonthlyBillModel bill, bool isDark) {
    Color statusBg = bill.isPaid ? AppColors.softLightGreen : (bill.isPartial ? AppColors.goldLight : AppColors.error.withOpacity(0.12));
    Color statusFg = bill.isPaid ? AppColors.success : (bill.isPartial ? AppColors.warning : AppColors.error);

    return Card(
      margin: const EdgeInsets.only(bottom: 12),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  bill.monthNameEn,
                  style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16),
                ),
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                  decoration: BoxDecoration(color: statusBg, borderRadius: BorderRadius.circular(6)),
                  child: Text(
                    bill.status,
                    style: TextStyle(fontSize: 10, fontWeight: FontWeight.bold, color: statusFg),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 6),
            Text(
              'Total Milk: ${bill.totalMilkLitres.toStringAsFixed(1)} Litres @ ₹${bill.appliedRate.toStringAsFixed(0)}/L',
              style: const TextStyle(fontSize: 12, color: AppColors.textMuted),
            ),
            const Divider(height: 16),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Milk Charges: ${CurrencyFormatter.format(bill.currentMonthMilkCharges)}', style: const TextStyle(fontSize: 11)),
                    Text('Prev Due: ${CurrencyFormatter.format(bill.previousBalance)} | Paid: ${CurrencyFormatter.format(bill.paidAmount)}', style: const TextStyle(fontSize: 11, color: AppColors.textMuted)),
                  ],
                ),
                Text(
                  CurrencyFormatter.format(bill.finalPayable),
                  style: TextStyle(
                    fontSize: 18,
                    fontWeight: FontWeight.bold,
                    color: bill.isPaid ? AppColors.success : AppColors.error,
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              mainAxisAlignment: MainAxisAlignment.end,
              children: [
                OutlinedButton.icon(
                  onPressed: () => _downloadPdf(context, bill),
                  icon: const Icon(Icons.picture_as_pdf_rounded, size: 16),
                  label: const Text('PDF Bill'),
                  style: OutlinedButton.styleFrom(padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6)),
                ),
                if (!bill.isPaid) ...[
                  const SizedBox(width: 8),
                  ElevatedButton.icon(
                    onPressed: () => _payNow(context, bill),
                    icon: const Icon(Icons.qr_code_rounded, size: 16),
                    label: Text(context.tr('pay_now')),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: AppColors.darkGreen,
                      foregroundColor: AppColors.pureWhite,
                      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 6),
                    ),
                  ),
                ],
              ],
            ),
          ],
        ),
      ),
    );
  }

  void _payNow(BuildContext context, MonthlyBillModel bill) async {
    final customer = await CustomerRepository().getCustomer(bill.customerId);
    if (customer == null || !context.mounted) return;

    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => UpiPaymentScreen(
          customer: customer,
          bill: bill,
          payableAmount: bill.finalPayable,
          ownerUpiId: 'owner@upi',
          dairyName: 'Smart Dairy',
        ),
      ),
    );
  }

  void _downloadPdf(BuildContext context, MonthlyBillModel bill) async {
    final customer = await CustomerRepository().getCustomer(bill.customerId);
    if (customer == null) return;

    final entries = await MilkEntryRepository().getCustomerEntriesForMonth(
      customerId: bill.customerId,
      year: bill.year,
      month: bill.month,
    );

    final dairy = DairySettingsModel(
      id: bill.ownerId,
      ownerId: bill.ownerId,
      dairyName: 'Smart Dairy',
      ownerName: 'Dairy Owner',
      ownerPhone: '',
      ownerUpiId: 'owner@upi',
      updatedAt: DateTime.now(),
    );

    final isMarathi = context.read<LocaleProvider>().isMarathi;
    final file = await PdfService.generateMonthlyBillPdf(
      customer: customer,
      bill: bill,
      dairy: dairy,
      monthEntries: entries,
      isMarathi: isMarathi,
    );

    await Printing.layoutPdf(
      onLayout: (_) => file.readAsBytes(),
      name: 'Bill_${customer.name}_${bill.yearMonth}',
    );
  }
}

